def _rules(text: str) -> set[str]:
    """The lines git acts on. Comments explain the rule; they are not the rule."""
    return {line.strip() for line in text.splitlines()
            if line.strip() and not line.lstrip().startswith("#")}


def test_the_generated_gitignore_does_not_ignore_what_the_gate_compares() -> None:
    rules = _rules(GITIGNORE)
    assert "/attest/*.json" not in rules, \
        "ignoring attest/*.json makes `git diff --exit-code attest/` compare nothing"
    assert {"/attest/run.json", "/attest/lean-emission.json"} <= rules


def test_git_itself_agrees(tmp_path: Path) -> None:
    """Asserted against real git, not against the text of the file.

    A rule can be present and still not do what it reads like — `/attest/`
    versus `/attest/*.json` versus a negation ordering — and this gate is only
    worth having if git's answer is the one being checked.
    """
    import subprocess

    subprocess.run(["git", "init", "-q"], cwd=tmp_path, check=True)
    (tmp_path / ".gitignore").write_text(GITIGNORE, encoding="utf-8")
    (tmp_path / "attest").mkdir()

    def ignored(rel: str) -> bool:
        return subprocess.run(["git", "check-ignore", "-q", rel],
                              cwd=tmp_path).returncode == 0

    assert ignored("attest/run.json"), "run/1.0 is provenance, not evidence"
    assert ignored("attest/lean-emission.json"), "the emitter's raw output is an input"
    for committed in ("attest/declarations.json", "attest/environment.json",
                      "attest/bundle.json", "attest/build.json"):
        assert not ignored(committed), \
            f"{committed} is what the gate compares; ignoring it makes the gate vacuous"


def test_the_generated_workflow_still_has_the_gate() -> None:
    assert "git diff --exit-code" in WORKFLOW
    assert "attest/" in WORKFLOW


def test_no_committed_generated_artifact_is_left_ignored(tmp_path: Path) -> None:
    """Every artifact the workflow writes is either ignored on purpose or diffed.

    The failure this guards against is a new artifact being added to the
    workflow and silently landing in neither category.
    """
    written = {"attest/lean-emission.json", "attest/environment.json",
               "attest/declarations.json"}
    ignored = {line.lstrip("/") for line in GITIGNORE.splitlines()
               if line.startswith("/attest/")}
    for artifact in written:
        assert artifact in ignored or "attest/" in WORKFLOW, artifact
    assert "attest/environment.json" not in ignored, \
        "environment.json is committed evidence and must be diffed"
