"""Tests for the volatile-property lint and the run/1.0 split — #160.

`git diff --exit-code attest/` is one of four claimed sorry-gates and the only
one that survives the seam. Two separate things were wrong with it:

1. **It could never pass.** `bundle.json` carried `produced_at` per predicate
   and `build.json` carried `produced_at` plus `ci{run_url, workflow_sha,
   runner}`. Both are committed and both changed every run, so the gate went
   red on no-op commits.
2. **It could never fail.** The generated `.gitignore` ignored `/attest/*.json`
   wholesale, so the diff compared nothing at all. A gate that cannot fail is
   not a weaker gate, it is a green step.

Fixing (1) without (2) would have produced a gate that passes for the wrong
reason, which is indistinguishable from the bug. Both are tested here.
"""

from __future__ import annotations

import json
from pathlib import Path

from contract.mfc.lint import (
    CI_REGENERATED_ARTIFACTS,
    VOLATILE_PROPERTY_NAMES,
    artifact_name,
    lint_volatile,
)
from contract.mfc.cli import EXIT_FINDINGS, EXIT_OK, main
from contract.mfc.scaffold import GITIGNORE, WORKFLOW
from contract.mfc.validate import SCHEMA_DIR

HERE = Path(__file__).resolve().parent
VALID_DIR = HERE.parent / "testdata" / "artifacts" / "valid"
INVALID_SCHEMAS = HERE.parent / "testdata" / "schemas" / "invalid"


# --------------------------------------------------------------------------
# The lint fires, and fires only where it should.
# --------------------------------------------------------------------------

def test_the_rejection_fixture_is_rejected() -> None:
    """A gate with no failing case is not evidence."""
    doc = json.loads((INVALID_SCHEMAS / "bundle-9.9.schema.json").read_text())
    findings = lint_volatile(doc, "bundle-9.9.schema.json")
    assert {f.name for f in findings} == {"produced_at", "run_url"}, \
        "the walk must reach $defs, not just top-level properties"


def test_the_shipped_schemas_are_clean() -> None:
    assert main(["lint-schemas", "--schema-dir", str(SCHEMA_DIR)]) == EXIT_OK


def test_lint_schemas_fails_on_the_rejection_fixtures() -> None:
    assert main(["lint-schemas", "--schema-dir", str(INVALID_SCHEMAS)]) == EXIT_FINDINGS


def test_an_uncommitted_artifact_may_carry_a_timestamp() -> None:
    """`emission` is regenerated every run and is NOT committed."""
    doc = json.loads((SCHEMA_DIR / "emission-1.0.schema.json").read_text())
    assert "emitted_at" in doc["properties"], "the premise of this test"
    assert lint_volatile(doc, "emission-1.0.schema.json") == []


def test_a_human_act_may_carry_its_own_date() -> None:
    """`reviewed_at` and `generated_at` are content, not run metadata.

    Both artifacts are committed, and neither is regenerated by CI on every
    commit — they are written by a deliberate human or offline act. The date a
    person reviewed a statement IS the fact being recorded, and banning it
    would delete evidence to protect a gate it does not threaten.
    """
    for name in ("review-1.0.schema.json", "resolution-1.0.schema.json"):
        doc = json.loads((SCHEMA_DIR / name).read_text())
        assert lint_volatile(doc, name) == []


def test_artifact_name_reads_the_filename() -> None:
    assert artifact_name("bundle-1.0.schema.json") == "bundle"
    assert artifact_name("aggregate-status.schema.json") == "aggregate"
    assert artifact_name("nonsense.json") == ""


def test_run_is_not_itself_policed() -> None:
    """run/1.0 is where the volatile fields were moved TO."""
    assert "run" not in CI_REGENERATED_ARTIFACTS
    doc = json.loads((SCHEMA_DIR / "run-1.0.schema.json").read_text())
    assert lint_volatile(doc, "run-1.0.schema.json") == []


