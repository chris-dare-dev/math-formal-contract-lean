def test_the_committed_schemas_no_longer_declare_what_moved() -> None:
    build = json.loads((SCHEMA_DIR / "build-1.0.schema.json").read_text())
    assert "produced_at" not in build["properties"]
    assert "ci" not in build["properties"]
    assert "ci" not in build["required"] and "produced_at" not in build["required"]

    bundle = json.loads((SCHEMA_DIR / "bundle-1.0.schema.json").read_text())
    predicate = bundle["$defs"]["predicate"]
    assert "produced_at" not in predicate["properties"]
    assert "produced_at" not in predicate["required"]


def test_run_1_0_carries_everything_that_moved() -> None:
    run = json.loads((SCHEMA_DIR / "run-1.0.schema.json").read_text())
    assert "produced_at" in run["properties"]
    assert set(run["properties"]["ci"]["properties"]) == {
        "run_url", "workflow_sha", "runner"}


def test_run_1_0_joins_back_to_the_committed_tree() -> None:
    """A release asset nobody can tie to a commit is not provenance."""
    run = json.loads((SCHEMA_DIR / "run-1.0.schema.json").read_text())
    files = run["properties"]["files"]
    assert files["minItems"] == 1, "a run that names no output is not a record of one"
    assert set(files["items"]["required"]) == {"file", "sha256"}


def test_the_contract_pin_stays_in_the_bundle() -> None:
    """`contract_repo.rev` is a PIN. A pin that changed per run is not pinning."""
    bundle = json.loads((SCHEMA_DIR / "bundle-1.0.schema.json").read_text())
    assert "contract_repo" in bundle["required"]


def test_every_valid_instance_still_validates() -> None:
    for path in sorted(VALID_DIR.glob("*.json")):
        assert main(["validate", str(path)]) == EXIT_OK, path.name


